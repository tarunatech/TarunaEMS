import {
  index,
  jsonb,
  numeric,
  pgEnum,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  uuid,
  varchar,
  integer,
} from 'drizzle-orm/pg-core';

export const amcContractStatusEnum = pgEnum('amc_contract_status', [
  'Draft',
  'Pending Approval',
  'Active',
  'Expired',
  'Cancelled',
  'Renewed',
]);

export const amcContracts = pgTable(
  'amc_contracts',
  {
    id: uuid('id').defaultRandom().primaryKey(),
    contractNumber: varchar('contractNumber', { length: 64 }).notNull(),
    title: varchar('title', { length: 255 }).notNull(),
    clientId: uuid('clientId').notNull(),
    clientName: varchar('clientName', { length: 255 }).notNull(),
    projectId: uuid('projectId'),
    projectCode: varchar('projectCode', { length: 64 }),
    projectName: varchar('projectName', { length: 255 }),
    contractType: varchar('contractType', { length: 32 }).notNull().default('New'),
    previousContractId: uuid('previousContractId'),
    status: amcContractStatusEnum('status').notNull().default('Draft'),
    startDate: varchar('startDate', { length: 32 }).notNull(),
    endDate: varchar('endDate', { length: 32 }).notNull(),
    durationMonths: integer('durationMonths').notNull().default(12),
    signingDate: varchar('signingDate', { length: 32 }),
    coverageType: varchar('coverageType', { length: 64 }).notNull().default('Comprehensive'),
    coveredEquipment: jsonb('coveredEquipment').notNull().default([]),
    coveredServices: jsonb('coveredServices').notNull().default([]),
    excludedServices: jsonb('excludedServices').notNull().default([]),
    preventiveVisitCount: integer('preventiveVisitCount').notNull().default(4),
    coverageNotes: text('coverageNotes'),
    contractValue: numeric('contractValue', { mode: 'number' }).notNull().default(0),
    currency: varchar('currency', { length: 10 }).notNull().default('INR'),
    billingFrequency: varchar('billingFrequency', { length: 32 }).notNull().default('Annual'),
    billingStartDate: varchar('billingStartDate', { length: 32 }),
    paymentTerms: varchar('paymentTerms', { length: 255 }),
    renewalTerms: text('renewalTerms'),
    commercialNotes: text('commercialNotes'),
    plannedInstallments: jsonb('plannedInstallments').notNull().default([]),
    documentPath: varchar('documentPath', { length: 1024 }),
    documentOriginalName: varchar('documentOriginalName', { length: 255 }),
    documentSize: integer('documentSize'),
    documentMimeType: varchar('documentMimeType', { length: 128 }),
    internalNotes: text('internalNotes'),
    approvedBy: uuid('approvedBy'),
    approvedAt: timestamp('approvedAt', { withTimezone: true }),
    createdBy: uuid('createdBy'),
    createdAt: timestamp('createdAt', { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp('updatedAt', { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => ({
    contractNumberUniqueIdx: uniqueIndex('amc_contracts_contractNumber_unique_idx').on(table.contractNumber),
    clientIdIdx: index('amc_contracts_clientId_idx').on(table.clientId),
    projectIdIdx: index('amc_contracts_projectId_idx').on(table.projectId),
    statusIdx: index('amc_contracts_status_idx').on(table.status),
    endDateIdx: index('amc_contracts_endDate_idx').on(table.endDate),
    previousContractIdIdx: index('amc_contracts_previousContractId_idx').on(table.previousContractId),
    createdAtIdx: index('amc_contracts_createdAt_idx').on(table.createdAt),
  })
);
